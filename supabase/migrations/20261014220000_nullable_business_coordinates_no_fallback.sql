-- Correct the original 20260228 migration that used central-Montreal coordinates
-- as defaults for every new business, even without verified geocoding.
-- Apply this forward-only migration to the real QMAPS project before rolling
-- out onboarding that can save a business with unknown coordinates.
--
-- Existing coordinates are NOT changed: an automated bulk rewrite could
-- destroy legitimate points. Audit historic default-coordinate rows separately.

alter table public.businesses
  alter column latitude drop not null,
  alter column longitude drop not null,
  alter column latitude drop default,
  alter column longitude drop default;

-- The geography column is generated by the existing sync trigger on writes.
-- Explicitly clear it when coordinates are incomplete; never leave a stale pin
-- after a merchant removes one coordinate.
create or replace function public.sync_business_derived_fields()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.latitude is not null and new.longitude is not null then
    new.location := ST_SetSRID(ST_MakePoint(new.longitude, new.latitude), 4326)::geography;
  else
    new.location := null;
  end if;

  new.search_document :=
    setweight(to_tsvector('simple', coalesce(new.name, '')), 'A') ||
    setweight(to_tsvector('simple', coalesce(new.description, '')), 'B') ||
    setweight(to_tsvector('simple', coalesce(new.address, '')), 'C') ||
    setweight(to_tsvector('simple', coalesce(new.city, '')), 'C');
  return new;
end;
$$;

